"""Write report.md from results.json and the case rows. Every number in the report comes from those two inputs.

Prose that interprets headroom results is kept in INTERPRETATION and printed only when results.json still has
the hash it was written against; otherwise the report says the interpretation is out of date.
"""

from __future__ import annotations

import hashlib
import json
from typing import Any

from common import OUT_DIR

CONDITION_NAMES = {
    "baseline": "Baseline: retrieved MinerU text (no recovery)",
    "clean_text": "(a) Clean ground-truth text, same retrieval",
    "gold_page_text": "(c) All MinerU text of the gold page(s), no retrieval",
    "gold_page_image": "(b) Baseline text plus gold page image(s)",
    "gold_page_image_only": "(b') Gold page image(s) only",
}
REPAIR_FOR = {
    "clean_text": "`correct_text` (perfect OCR text; can also change retrieval)",
    "gold_page_text": "`retry_retrieval` (perfect page choice, OCR unchanged)",
    "gold_page_image": "`invoke_vlm` (perfect page choice; same text plus image)",
    "gold_page_image_only": "none (image replaces OCR text)",
}
CAUSE_TEXT = {
    "scoring_artifact": "Answer correct, EM cannot see it (wording, units, list format, notation, Unicode)",
    "gold_or_question": "Gold answer or question questionable; reply defensible",
    "ocr_lost": "OCR lost the evidence (empty, partial or invented text)",
    "ocr_damaged": "OCR damaged the evidence (garbled fraction or name)",
    "retrieval_miss_page": "Evidence intact; its page not retrieved",
    "retrieval_miss_passage": "Evidence intact; page retrieved, passage not",
    "model_error": "Evidence in the prompt and intact; model wrong, partial or abstained",
}

# Interpretation written after reading results.json; shown only while the hash matches.
INTERPRETATION_FOR_SHA256 = None
INTERPRETATION = ""


def pct(x: float | None, digits: int = 1) -> str:
    return "n/a" if x is None else f"{100 * x:.{digits}f}"


def num(x: float | None, digits: int = 3) -> str:
    return "n/a" if x is None else f"{x:.{digits}f}"


def ci(entry: dict[str, float]) -> str:
    return f"{100 * entry['diff']:+.1f} [{100 * entry['ci_low']:+.1f}, {100 * entry['ci_high']:+.1f}]"


def write(results: dict[str, Any], rows: list[dict[str, Any]]) -> None:
    raw = json.dumps(results, sort_keys=True, ensure_ascii=False, default=dict).encode()
    sha = hashlib.sha256(raw).hexdigest()
    n, fails = results["questions"], results["failures"]
    part = results["baseline_partition"]
    cond = results["conditions"]
    base = cond["baseline"]
    headroom = [c for c in ("clean_text", "gold_page_text", "gold_page_image", "gold_page_image_only") if c in cond]
    pending = [c for c in ("clean_text", "gold_page_text", "gold_page_image", "gold_page_image_only") if c not in cond]
    L: list[str] = []
    a = L.append
    a("# Why the gpt-6.1-terra baseline fails on ohr_dev_v1, and how much each repair could gain")
    a("")
    a(f"Generated by `scripts/analysis/ohr_dev_v1_failures/analyse.py` from `results.json` (sha256 `{sha[:12]}`). "
      "Rerun that command to regenerate it. Development data only: 70 questions from 30 documents, not a scientific evaluation.")
    a("")
    a("## What is measured, what is interpretation, what is unverified")
    a("")
    a("- **Measured** (from run records and fixed formulas): official EM and F1, ANLS, page recall@k, retrieval LCS, "
      "edit distance between MinerU and the clean reference text, and every headroom score, interval and test below.")
    a("- **Interpretation** (one coder's judgement): every code in `coding_agent_v2.csv` (codebook v2), so the failure breakdown, the "
      "evidence-impact counts and the repair a case points to. The coder is an AI agent, not a person. No second "
      "labeller has coded the cases yet, so agreement is unknown.")
    a("- **Unverified**: whether the codes agree with a human labeller; whether results hold beyond these 70 questions; "
      "how the undated `gpt-6.1-terra` alias behaves on a rerun; the image token price of that model; and the exact "
      "edit-distance normalisation behind the OHR-Bench paper's MinerU number, which its released code does not contain.")
    if pending:
        a(f"- **Pending**: headroom runs not yet completed: {', '.join('`' + p + '`' for p in pending)}. Their rows below say so.")
    a("")
    a("## 1. Baseline")
    a("")
    a(f"Run `2026-10-31-ohr-dev-v1-baseline-terra-r1`: {n} questions, EM {num(base['em'])}, F1 {num(base['f1'])}, "
      f"ANLS {num(base['anls'])}. {part['exact']} exact, {part['partial']} partial (F1 > 0), {part['zero']} zero. "
      f"The {fails} non-exact cases are coded below.")
    a("")
    a("## 2. Failure breakdown")
    a("")
    a("Each case has one primary cause, chosen in the order of `codebook_v2.md` section 5 (answer and gold checks first, "
      "then the pipeline from OCR to retrieval to the model).")
    a("")
    a("| Primary cause | Cases | of 55 | F1 > 0 | F1 = 0 | Mean baseline F1 | Mean ANLS |")
    a("| --- | ---: | ---: | ---: | ---: | ---: | ---: |")
    for cause, text in CAUSE_TEXT.items():
        k = results["primary_cause"][cause]
        split = results["primary_cause_by_f1"][cause]
        a(f"| {text} | {k} | {pct(k / fails, 0)}% | {split['partial']} | {split['zero']} | "
          f"{num(results['f1_by_cause'][cause], 2)} | {num(results['anls_by_cause'][cause], 2)} |")
    a("")
    sa, gq = results["primary_cause"]["scoring_artifact"], results["primary_cause"]["gold_or_question"]
    ocr = results["primary_cause"]["ocr_lost"] + results["primary_cause"]["ocr_damaged"]
    a(f"Read with the coding caveat above: {sa} of {fails} failures are correct answers that EM scores 0, and {gq} more "
      f"rest on a questionable gold answer or question. OCR is the primary cause in {ocr} cases "
      f"({results['primary_cause']['ocr_lost']} lost, {results['primary_cause']['ocr_damaged']} damaged), retrieval in "
      f"{results['primary_cause']['retrieval_miss_page'] + results['primary_cause']['retrieval_miss_passage']} "
      f"({results['primary_cause']['retrieval_miss_page']} page-level, {results['primary_cause']['retrieval_miss_passage']} passage-level), and the model in {results['primary_cause']['model_error']}. "
      f"If the coder's correctness judgements hold, {part['exact'] + sa} of {n} questions "
      f"({pct((part['exact'] + sa) / n, 0)}%) were answered correctly, against an official EM of {pct(base['em'], 1)}%.")
    a("")
    a("The three observations of study brief section 3, kept apart (counts over the 55 failures):")
    a("")
    td = results["text_defect_labels"]
    a("- **Text defect** (page image against MinerU, several labels per case allowed): " +
      ", ".join(f"`{k}` {v}" for k, v in sorted(td.items(), key=lambda kv: -kv[1])) + ".")
    ei = results["evidence_impact"]
    a("- **Evidence impact** (does the needed passage survive in MinerU): " +
      ", ".join(f"`{k}` {ei.get(k, 0)}" for k in ("survives", "damaged", "lost", "uncertain")) + ".")
    a("- **Repair effect**: measured only by the headroom runs in section 4, not by the codes.")
    gf = results["gold_flags"]
    a("- **Gold and question flags**: " + (", ".join(f"`{k}` {v}" for k, v in sorted(gf.items(), key=lambda kv: -kv[1])) or "none") + ".")
    a("")
    a("A damaged page does not mean a failure caused by OCR. Of the cases whose evidence survives, many sit on pages with "
      "lost structure or word corruption, and the model still found the passage.")
    a("")
    a("## 3. Measurements per case")
    a("")
    r = results["retrieval"]
    a("### Retrieval")
    a("")
    a(f"Page recall over all {n} questions (no request counts as 0): @1 {num(r['page_recall_at_k_all']['1'], 2)}, "
      f"@3 {num(r['page_recall_at_k_all']['3'], 2)}, @5 {num(r['page_recall_at_k_all']['5'], 2)}. "
      f"Only the {r['multipage_questions']} questions on multi-page documents test page choice; for them recall is "
      f"@1 {num(r['page_recall_at_k_multipage_docs']['1'], 2)}, @3 {num(r['page_recall_at_k_multipage_docs']['3'], 2)}, "
      f"@5 {num(r['page_recall_at_k_multipage_docs']['5'], 2)}. On single-page documents page recall is 1 by construction.")
    a("")
    a(f"Passage coverage, over the {r['sent']} questions that sent a request: OHR-Bench's own retrieval metric (word-level "
      f"LCS of the gold evidence context in the retrieved text, copied from upstream `lcs_score`) averages "
      f"{num(r['retrieval_lcs_top5_sent'], 2)} for the 5 chunks sent and {num(r['retrieval_lcs_top2_sent'], 2)} for the top 2. "
      f"Upstream splits on spaces, so unspaced Chinese text and MinerU's dropped spaces score near 0 even when the passage is there. "
      f"The same ratio over characters (FAAR-defined) averages {num(r['retrieval_lcs_chars_top5_sent'], 2)}, and "
      f"{r['passage_included_chars_lcs95']} of {n} questions pass the paper's 0.95 inclusion threshold on it. "
      "The character version agrees with the coder's `passage_in_prompt` judgement on most cases (see `case_measures.csv`). "
      "No lead-approved passage-matching rule exists yet (brief section 3), so treat both as diagnostics.")
    a("")
    o = results["ocr"]
    a("### OCR quality on the gold evidence pages")
    a("")
    a(f"{o['evidence_pages']} distinct evidence pages, {o['empty_pages']} with empty MinerU text. Normalised edit distance "
      f"(Levenshtein over the longer string, whitespace collapsed) averages {num(o['mean_ned'], 2)} over all of them and "
      f"{num(o['mean_ned_nonempty'], 2)} over non-empty pages (median {num(o['median_ned_nonempty'], 2)}). Character error "
      f"rate (over the reference length) averages {num(o['mean_cer'], 2)}; it exceeds 1 where MinerU invents text. "
      f"Pages with Chinese text average {num(o['mean_ned_han_pages'], 2)}, the others {num(o['mean_ned_other_pages'], 2)}.")
    a("")
    a("| Domain | Mean NED |")
    a("| --- | ---: |")
    for t, v in o["ned_by_doc_type"].items():
        a(f"| {t} | {num(v, 2)} |")
    a("")
    a(f"By evidence impact, mean CER is {num(o['cer_by_impact']['survives'], 2)} where the evidence survives, "
      f"{num(o['cer_by_impact']['damaged'], 2)} where it is damaged and {num(o['cer_by_impact']['lost'], 2)} where it is lost. "
      "Page-level edit distance is a weak signal for one question, though. On the newspaper pages the clean reference "
      "itself has duplicated column fragments and character errors that MinerU does not, so a high distance there partly "
      "measures the reference, not MinerU.")
    a("")
    a("### Softer answer score")
    a("")
    a(f"ANLS (threshold 0.5, lowercase, FAAR-defined secondary metric) is {num(base['anls'])} against EM {num(base['em'])} "
      f"and F1 {num(base['f1'])}. ANLS gives no credit to long correct answers, because it compares whole strings, so it "
      "does not recover the scoring artifacts either: a unit suffix on a short number (`108幅` against `108`) costs half "
      "the string. Neither F1 nor ANLS is a correctness judgement.")
    a("")
    a("## 4. Headroom per repair type")
    a("")
    a("Each condition answers the same 70 questions with the same model, settings and prompt template; only the evidence "
      "changes. Every condition uses evaluation-only inputs (clean text or gold page labels), so each is an upper bound "
      "for one repair, never a method. Differences are condition minus baseline, in points, with 95% paired bootstrap "
      "intervals: first resampling the 30 documents (the brief's rule), then resampling questions for reference. "
      "McNemar's exact test is on EM.")
    a("")
    a("| Condition | Bounds | EM | F1 | ANLS | ΔEM, by document | ΔEM, by question | ΔF1, by document | McNemar gained / lost, p | Cost USD |")
    a("| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
    a(f"| {CONDITION_NAMES['baseline']} | | {num(base['em'])} | {num(base['f1'])} | {num(base['anls'])} | | | | | 0.086 (baseline run) |")
    for c in ("clean_text", "gold_page_text", "gold_page_image", "gold_page_image_only"):
        if c not in cond:
            a(f"| {CONDITION_NAMES[c]} | {REPAIR_FOR[c]} | pending | | | | | | | |")
            continue
        e = cond[c]
        m = e["mcnemar_em"]
        a(f"| {CONDITION_NAMES[c]} | {REPAIR_FOR[c]} | {num(e['em'])} | {num(e['f1'])} | {num(e['anls'])} | "
          f"{ci(e['paired']['em']['by_document'])} | {ci(e['paired']['em']['by_question'])} | {ci(e['paired']['f1']['by_document'])} | "
          f"{m['gained']} / {m['lost']}, p = {m['p_value']:.3g} | {e['cost_usd']:.3f} |")
    a("")
    if headroom:
        a("Failures turned into exact matches, by the coded primary cause (and baseline exact matches lost):")
        a("")
        a("| Condition | " + " | ".join(f"`{c}` ({results['primary_cause'][c]})" for c in CAUSE_TEXT) + " | Broke an exact match |")
        a("| --- | " + " | ".join("---:" for _ in CAUSE_TEXT) + " | ---: |")
        for c in headroom:
            fx = cond[c]["fixed_by_cause"]
            a(f"| {CONDITION_NAMES[c]} | " + " | ".join(str(fx[k]) for k in CAUSE_TEXT) + f" | {cond[c]['broke_baseline_exact']} |")
        a("")
        a(f"Best of all conditions per question in hindsight (a diagnostic bound, not a policy): EM {num(results.get('best_in_hindsight_em'))}.")
        a("")
    if INTERPRETATION and INTERPRETATION_FOR_SHA256 == sha:
        a("### Interpretation")
        a("")
        a(INTERPRETATION)
        a("")
    elif headroom:
        a("_The written interpretation of these results is missing or out of date for this `results.json`._")
        a("")
    p = results["power"]
    icc = results["icc_baseline_em"]
    a("## 5. Sample size for a 5-point EM gain")
    a("")
    a(f"For a paired comparison of a repair policy with the baseline on the same questions, McNemar's test at two-sided "
      f"alpha {p['alpha']} and power {p['power']} needs the number of questions below to detect an EM gain of "
      f"{pct(p['delta'], 0)} points. The answer depends on how often the two policies disagree (the discordant rate). "
      f"The second column inflates it by the document design effect estimated from the baseline "
      f"(ICC of EM within documents {num(icc['icc'], 2)}, mean {num(icc['mean_cluster_size'], 1)} questions per document, "
      f"design effect {num(icc['design_effect'], 2)}).")
    a("")
    a("| Discordant rate | Questions | With design effect |")
    a("| ---: | ---: | ---: |")
    for row in p["table"]:
        a(f"| {pct(row['discordant_rate'], 1)}% | {row['questions'] or 'n/a'} | {row['questions_with_design_effect'] or 'n/a'} |")
    a("")
    if p["observed_discordant_rates"]:
        a("Observed discordant rates against the baseline: " + ", ".join(
            f"{CONDITION_NAMES[k]} {pct(v, 1)}%" for k, v in p["observed_discordant_rates"].items()) +
          ". A real repair touches fewer questions than an oracle condition, so its discordant rate is likely lower. "
          "A lower rate needs fewer questions for the same gain, but a real repair's gain is also likely smaller than 5 points.")
    else:
        a("No headroom run has finished, so no discordant rate has been observed; the rows are assumptions.")
    a("")
    a("The pilot's 70 questions cannot detect a 5-point gain at any of these rates.")
    a("")
    a("## 6. Comparison with the OHR-Bench paper")
    a("")
    a("Zhang et al., *OCR Hinders RAG* (ICCV 2025), Table 2, report MinerU with page edit distance 0.24 (ground truth "
      "has none), retrieval LCS 50.1 over all evidence types against 70.0 for ground truth, generation F1 36.7 against 43.9 "
      "with the gold page given, and overall F1 30.0 against 36.1 with retrieval. The relative overall loss from MinerU "
      "is about 17%.")
    a("")
    a("| | OHR-Bench paper (MinerU) | This analysis |")
    a("| --- | --- | --- |")
    a(f"| OCR edit distance | 0.24 (mean per page; normalisation not in the released code) | {num(o['mean_ned_nonempty'], 2)} mean NED over the {o['evidence_pages'] - o['empty_pages']} non-empty evidence pages, {num(o['mean_ned'], 2)} with the {o['empty_pages']} empty pages counted as 1 |")
    a(f"| Retrieval LCS | 50.1 (all types, top-2) | {pct(r['retrieval_lcs_top2_all'])} (same formula, top-2, all 70; {pct(r['retrieval_lcs_top5_all'])} top-5) |")
    gt = cond.get("clean_text")
    a(f"| Overall F1, MinerU | 30.0 | {pct(base['f1'])} |")
    a(f"| Overall F1, clean text | 36.1 | {pct(gt['f1']) if gt else 'pending'} |")
    gp = cond.get("gold_page_text")
    a(f"| Generation F1 with the gold page, MinerU | 36.7 | {pct(gp['f1']) if gp else 'pending'} |")
    a("")
    a("The setups differ in ways that move every number, so only the direction of the MinerU-to-clean gap is comparable:")
    a("")
    a("- **Answer model.** The paper averages Qwen2-7B and Llama-3.1-8B; this run uses `gpt-6.1-terra`, a much larger model, with a short-answer prompt.")
    a("- **Retrieval.** The paper searches a whole domain's knowledge base (BGE-M3 and BM25, averaged) and passes the top 2 chunks of 1,024 tokens. This run searches only the question's own document (23 of 30 are single pages) with a hybrid retriever and passes 5 chunks of 180 words.")
    a("- **Questions.** The paper uses all 8,498 questions across five evidence types. This pilot has 70 train-split questions, no charts, 22 Han-script questions, and 6 questions whose evidence page MinerU left empty.")
    a("- **Metrics.** The paper reports F1 (and LCS for retrieval) and drops blank answers before averaging; this report keeps every question, counts abstentions as 0 and adds EM and ANLS.")
    a("- **MinerU version.** Both use the MinerU output distributed with OHR-Bench, whose version and settings are unknown.")
    a("")
    a("## 7. Limitations")
    a("")
    a("- One agent coded all cases. The codebook was drafted after reading the cases, then fixed before coding; that is "
      "normal for a first codebook but means the categories fit this sample.")
    a("- 70 questions from 30 documents, chosen by a purposive quota. Counts describe this sample, not OHR-Bench.")
    a("- The clean reference text is OHR-Bench's transcription. On several pages it is worse than MinerU, and some gold "
      "answers and one question copy its errors.")
    a("- Headroom conditions use gold labels or clean text, so they bound a repair from above; they are not a repair.")
    a("- `gpt-6.1-terra` is an undated alias. All runs used it on 2026-10-31.")
    a("")
    a("## Files")
    a("")
    a("- `codebook_v2.md`: the codebook these codes use. It lists its two changes from v1.")
    a("- `coding_agent_v2.csv`: the agent's codes for the 55 failures under v2.")
    a("- `codebook.md` and `coding_agent_v1.csv`: v1 and its codes, kept unchanged as the record.")
    a("- `failure_table.csv`: codes next to measurements, gold answer and reply, one row per failure.")
    a("- `case_measures.csv`: all 70 questions with retrieval, OCR and score measurements per condition.")
    a("- `results.json`: every aggregate in this report.")
    a("- `packet/index.html` and `packet/labeller_form.csv`: the blind packet for a second labeller (git-ignored; regenerated by `analyse.py`).")
    a("- `agreement.py`: Cohen's kappa between the agent codes and a filled form.")
    (OUT_DIR / "report.md").write_text("\n".join(L) + "\n", encoding="utf-8")
